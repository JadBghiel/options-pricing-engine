"""benchmark json -> markdown tables in benchmarks/RESULTS.md, run by benchmarks/run.sh

usage: python benchmarks/report.py build/bench
"""

import json
import platform
import sys
from pathlib import Path
from typing import Any

import ope
from ope import _core

IMPLS = ["pure_python", "numpy", "cpp_1_thread", "cpp_all_threads"]
HEADERS = ["Pure Python", "NumPy", "C++ 1 thread", f"C++ {_core.hardware_threads()} threads"]
WORKLOADS = {
    "black_scholes": "Black-Scholes, 100,000 calls",
    "monte_carlo": "Monte Carlo, 1,000,000 paths",
    "american_tree": "American put, CRR tree, 2,000 steps",
}


def _ms(seconds: float) -> str:
    ms = seconds * 1e3
    return f"{ms:,.0f} ms" if ms >= 100 else f"{ms:.1f} ms" if ms >= 1 else f"{ms:.2f} ms"


def _cpu() -> str:
    for line in Path("/proc/cpuinfo").read_text().splitlines():
        if line.startswith("model name"):
            return line.split(":", 1)[1].strip()
    return platform.processor() or "unknown cpu"


def python_table(data: dict[str, Any]) -> str:
    medians: dict[tuple[str, str], float] = {}
    for b in data["benchmarks"]:
        workload, impl = b["param"].split("-")  # the test id, e.g. monte_carlo-numpy
        medians[(workload, impl)] = b["stats"]["median"]
    rows = [
        "| Workload | " + " | ".join(HEADERS) + " | C++ vs NumPy |",
        "|---|" + "---:|" * (len(HEADERS) + 1),
    ]
    for key, label in WORKLOADS.items():
        cells = [_ms(medians[(key, i)]) if (key, i) in medians else "n/a" for i in IMPLS]
        best = min(medians[(key, i)] for i in IMPLS[2:] if (key, i) in medians)
        ratio = medians[(key, "numpy")] / best
        rows.append(f"| {label} | " + " | ".join(cells) + f" | {ratio:.1f}x |")
    return "\n".join(rows)


def cpp_table(data: dict[str, Any]) -> str:
    rows = ["| Benchmark | Threads | Median time | Speedup vs 1 thread |", "|---|---:|---:|---:|"]
    one: dict[str, float] = {}
    for b in data["benchmarks"]:
        if b.get("aggregate_name") != "median":
            continue
        name, _, arg = b["run_name"].partition("/")
        threads = int(arg.split(":")[1].split("/")[0]) if arg.startswith("threads") else 1
        t = b["real_time"] / 1e3  # ms -> s
        one.setdefault(name, t)
        rows.append(f"| {name[3:]} | {threads} | {_ms(t)} | {one[name] / t:.2f}x |")
    return "\n".join(rows)


def main(out_dir: str) -> None:
    out = Path(out_dir)
    py = json.loads((out / "python.json").read_text())
    cc = json.loads((out / "cpp.json").read_text())
    text = f"""# Benchmark results

Generated by `bash benchmarks/run.sh` (do not edit by hand). Median of several runs, Release
build ({_core.compiler}), on {_cpu()}, {_core.hardware_threads()} hardware threads, Python
{platform.python_version()}, NumPy {__import__("numpy").__version__}, ope {ope.__version__}.

## From Python (pytest-benchmark)

What a Python user gets: each call includes the Python to C++ crossing. "NumPy" is the library
itself (`ope.price`, `ope.mc_price`, `ope.crr_price`). The tree has no multithreaded version:
each time step needs the one after it, so there is nothing to split.

{python_table(py)}

## Inside C++ (Google Benchmark)

No Python in the way. Thread scaling of the Monte Carlo and of the Black-Scholes chain.

{cpp_table(cc)}
"""
    Path("benchmarks/RESULTS.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/bench")
